-- Two gaps closed together, because neither is safe alone. The table is the
-- target of foreign keys from profiles.default_country_code and
-- shops.country_code, so it decides what can be saved, not just what the
-- picker offers — and a country missing from it is a save that fails. The
-- ratings table meanwhile had no constraint at all, which left the column on
-- every rating as free text while the two rare writes were policed.
--
-- The list is ISO 3166-1 alpha-2 as the browser’s own CLDR data has it, minus
-- two groups. Entries that are not places: the European Union, the Eurozone,
-- the United Nations, Outlying Oceania, Unknown Region, and the two
-- pseudo-locales used for translation testing. And withdrawn codes, which CLDR
-- still resolves to whatever succeeded them — DD gives “Germany”, SU gives
-- “Russia”, UK duplicates GB — so leaving them in would list a dozen countries
-- twice and let someone file a rating from East Germany. 257 rows, every
-- name distinct.
--
-- Additive by construction. A code already present is left exactly as it is,
-- names included, so a deployed row that spells a country differently keeps
-- its spelling and nothing is overwritten.

