-- milk_tests.country_code joins the other two under the same constraint.
--
-- Guarded rather than asserted: if any rating carries a code the table does
-- not have, adding the constraint would abort the whole migration and block
-- the deploy. It skips with a notice instead, so the seed still lands and the
-- offending rows can be looked at. Every one of the 350 rows deployed today
-- resolves, so this is expected to fire.
DO $$
DECLARE
  orphans integer;
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'milk_tests_country_code_fkey'
  ) THEN
    RAISE NOTICE 'milk_tests.country_code is already constrained; nothing to do.';
    RETURN;
  END IF;

  SELECT count(*) INTO orphans
  FROM public.milk_tests m
  WHERE m.country_code IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM public.countries c WHERE c.code = m.country_code);

  IF orphans > 0 THEN
    RAISE NOTICE 'Skipping milk_tests.country_code foreign key: % row(s) hold a code that is not in countries.', orphans;
    RETURN;
  END IF;

  ALTER TABLE public.milk_tests
    ADD CONSTRAINT milk_tests_country_code_fkey
    FOREIGN KEY (country_code) REFERENCES public.countries(code);
END $$;
